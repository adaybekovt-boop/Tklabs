test("v0.24 Kazakhstan exactness benchmark contains 150 routing cases", () => {
  assert.equal(MUST_GROUND.length + MUST_NOT_GROUND.length, 150);
  assert.ok(MUST_GROUND.length >= 100);
});

test("v0.24 Kazakhstan exactness benchmark sends factual cases to verified web routes", () => {
  for (const query of MUST_GROUND) {
    const route = routeErmaTask(query);
    assert.equal(route.toolClass, "web", `${query} => ${route.intent}/${route.toolClass}`);
    assert.equal(route.verification, "verify-sources", `${query} must require source verification`);
    assert.equal(route.shouldCiteSources, true, `${query} must cite sources`);
  }
});

test("v0.24 Kazakhstan exactness benchmark keeps non-factual work off automatic web grounding", () => {
  for (const query of MUST_NOT_GROUND) {
    const route = routeErmaTask(query);
    assert.notEqual(route.toolClass, "web", `${query} unexpectedly routed to web as ${route.intent}`);
  }
});
